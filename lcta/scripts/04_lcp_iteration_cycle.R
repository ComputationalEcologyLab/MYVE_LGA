## ============================================================================
## LCP iteration cycle -- one call to run_lcp_iteration():
##   1. predicts iteration (N-1)'s model onto the landscape)
##   2. builds LCP lines from resistance surface (gdistance, uses lcp_tools.R)
##   3. extracts covariates along the new LCP lines (01_extract_covariates.R)
##   4. fits iteration N's model (fit_tools.R) and saves it
##
## Iteration N's model is fit from LCP lines generated by iteration
## (N-1)'s model; iteration 1 uses the straight-line (iteration 0) model
## from 03_fit_straight_line.R.
##
## ============================================================================

# Load packages
sapply(c("dplyr", "parallel", "foreach", "doParallel"), 
       require, 
       character.only = T)

source("lcta/scripts/lcp_tools.R")

## ---- User configure ----
response_col  <- "gd"       
model_dir     <- "lcta/models/"      # straight-line will be iteration 0
lines_dir     <- "lcta/outputs/lcp_lines/"
n_iterations  <- 5              # Number of LCP iterations after the straight-
                                # line model
FORCE_RECOMPUTE <- FALSE        # if TRUE, recomputes every iteration from 
                                # scratch even if its output files already exist
noCLS         <- 60
## ---------------------------------------------------------------

dir.create(model_dir, recursive = TRUE, showWarnings = FALSE)
dir.create(lines_dir, recursive = TRUE, showWarnings = FALSE)

folds             <- readRDS("lcta/results/bat_cv_folds.rds")

# Change this if it gets updated along the way
selection_results <- readRDS("lcta/results/bat_variable_selection.rds")

pairs <- readRDS("lcta/data/samples_pairwise.rds") %>%  
  dplyr::mutate(index = dplyr::row_number())

predictor_cols <- selection_results$selected_vars
sub_pairs      <- pairs %>% dplyr::filter(index %in% folds$orig_index)
domain         <- folds$model_domain

model_path <- function(iteration, dir = model_dir) paste0(dir, "lcp_", iteration, ".rds")
lines_path <- function(iteration, dir = lines_dir) paste0(dir, "lcp_", iteration, ".rds")

## ----------------------------------------------------------------------
## One full LCP refinement round
## ----------------------------------------------------------------------
run_lcp_iteration <- function(iteration) {

  message("LCP iteration ", iteration)

  prev_fit <- readRDS(model_path(iteration - 1))

  forced_value <- if (!is.null(FORCED_VAR) && FORCED_VAR %in% predictor_cols) {
    stats::median(sub_pairs[[FORCED_VAR]])
  } else {
    NA_real_
  }

  resistance <- predict_resistance_surface(prev_fit, predictor_cols, forced_value, domain)

  cl <- parallel::makeCluster(noCLS)
  doParallel::registerDoParallel(cl)

  sub_data <- tryCatch({
    lcp_lines <- compute_lcp_lines(resistance, sub_pairs, domain)
    saveRDS(lcp_lines, lines_path(iteration))

    ## already_buffered = TRUE -- lcp_lines came out of compute_lcp_lines()
    sd <- extract_covariates(lcp_lines, sub_pairs, already_buffered = TRUE)
    stopifnot(nrow(sd) == folds$n_pairs)
    sd
  }, finally = {
    parallel::stopCluster(cl)
    foreach::registerDoSEQ()
  })

  fit <- fit_gbm_cv(sub_data, predictor_cols, response_col, folds)
  saveRDS(fit, model_path(iteration))
}

## ----------------------------------------------------------------------
## Iteration N reads iteration (N-1)'s model, saved above.
## ----------------------------------------------------------------------
for (iteration in seq_len(n_iterations)) {

  already_done <- !FORCE_RECOMPUTE && file.exists(model_path(iteration)) && file.exists(lines_path(iteration))

  if (already_done) {
    message("Iteration ", iteration, ": already computed, skipping (set FORCE_RECOMPUTE <- TRUE to redo).")
    next
  }

  run_lcp_iteration(iteration)
  gc()
}

message("Done: ", n_iterations, " LCP iteration(s) completed.")
